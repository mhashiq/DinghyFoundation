let currentLang = localStorage.getItem('dinghy_lang') || 'en';

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (translations[lang]) {
    currentLang = lang;
    localStorage.setItem('dinghy_lang', lang);
    applyTranslations();
  }
}

export function applyTranslations() {
  const dict = translations[currentLang];
  
  // Toggle html lang attribute and font family
  document.documentElement.lang = currentLang;
  if (currentLang === 'bn') {
    document.body.classList.add('font-bangla');
    document.body.classList.remove('font-english');
  } else {
    document.body.classList.add('font-english');
    document.body.classList.remove('font-bangla');
  }

  // Find all elements with data-i18n
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        if (el.getAttribute('placeholder')) {
          el.placeholder = dict[key];
        } else {
          el.value = dict[key];
        }
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // Update language toggle button text
  const langBtns = document.querySelectorAll('.lang-toggle-btn');
  langBtns.forEach(btn => {
    btn.textContent = dict.nav_lang;
  });
}
